import pg from 'pg'
import { normalizeLifeEvent } from './job-intelligence.mjs'
import {
  DEFAULT_COMPANION_SETTINGS,
  getDueEventReminders,
  nextOccurrenceDate,
  normalizeCompanionSettings,
  zonedDateTimeToDate,
} from './companion-intelligence.mjs'

const { Pool } = pg

export class PostgresCompanionStore {
  constructor(pool) {
    this.pool = pool
  }

  static async open(connectionString) {
    const pool = new Pool({
      connectionString,
      max: 5,
      connectionTimeoutMillis: 10000,
      idleTimeoutMillis: 10000,
    })
    const store = new PostgresCompanionStore(pool)
    try {
      await store.initialize()
      return store
    } catch (error) {
      await pool.end()
      throw error
    }
  }

  async initialize() {
    await this.pool.query(`
      CREATE TABLE IF NOT EXISTS companion_settings (
        id INTEGER PRIMARY KEY CHECK (id = 1),
        settings_json JSONB NOT NULL DEFAULT '{}'::jsonb,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
      );
      INSERT INTO companion_settings(id) VALUES (1) ON CONFLICT (id) DO NOTHING;
      CREATE TABLE IF NOT EXISTS personal_events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        description TEXT NOT NULL DEFAULT '',
        category TEXT NOT NULL DEFAULT 'Custom event',
        event_date DATE NOT NULL,
        event_time TEXT NOT NULL DEFAULT '',
        timezone TEXT NOT NULL DEFAULT 'Asia/Kolkata',
        recurrence TEXT NOT NULL DEFAULT 'None',
        reminder_minutes_json JSONB NOT NULL DEFAULT '[0]'::jsonb,
        importance TEXT NOT NULL DEFAULT 'Medium',
        active BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        last_notified_at TIMESTAMPTZ,
        next_occurrence DATE NOT NULL
      );
      CREATE INDEX IF NOT EXISTS personal_events_due ON personal_events(active, next_occurrence);
      CREATE TABLE IF NOT EXISTS companion_notifications (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        idempotency_key TEXT NOT NULL UNIQUE,
        notification_type TEXT NOT NULL,
        title TEXT NOT NULL,
        message TEXT NOT NULL,
        scheduled_at TIMESTAMPTZ NOT NULL,
        status TEXT NOT NULL DEFAULT 'pending',
        attempts INTEGER NOT NULL DEFAULT 0,
        available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        lease_until TIMESTAMPTZ,
        last_error TEXT NOT NULL DEFAULT '',
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        delivered_at TIMESTAMPTZ
      );
      CREATE INDEX IF NOT EXISTS companion_notifications_history
        ON companion_notifications(created_at DESC);
      CREATE TABLE IF NOT EXISTS companion_calendar_cache (
        region TEXT NOT NULL,
        year INTEGER NOT NULL,
        events_json JSONB NOT NULL,
        fetched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        PRIMARY KEY(region, year)
      );
      CREATE TABLE IF NOT EXISTS companion_runs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        scheduler_name TEXT NOT NULL,
        trigger TEXT NOT NULL,
        status TEXT NOT NULL,
        started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        completed_at TIMESTAMPTZ,
        duration_ms INTEGER NOT NULL DEFAULT 0,
        delivered_count INTEGER NOT NULL DEFAULT 0,
        error TEXT NOT NULL DEFAULT ''
      );
      CREATE INDEX IF NOT EXISTS companion_runs_history ON companion_runs(id DESC);
    `)
  }

  async getCompanionSettings() {
    const { rows } = await this.pool.query('SELECT settings_json FROM companion_settings WHERE id = 1')
    return normalizeCompanionSettings(rows[0]?.settings_json || {}, DEFAULT_COMPANION_SETTINGS)
  }

  async saveCompanionSettings(input = {}) {
    const settings = normalizeCompanionSettings(input, await this.getCompanionSettings())
    await this.pool.query(`UPDATE companion_settings
      SET settings_json = $1::jsonb, updated_at = now() WHERE id = 1`, [JSON.stringify(settings)])
    return settings
  }

  async enqueueCompanionNotification(input) {
    await this.pool.query(`INSERT INTO companion_notifications(
      idempotency_key, notification_type, title, message, scheduled_at, available_at
    ) VALUES ($1, $2, $3, $4, $5, $6)
    ON CONFLICT (idempotency_key) DO NOTHING`, [
      input.idempotencyKey,
      input.type,
      input.title,
      input.message,
      input.scheduledAt || new Date(),
      input.availableAt || new Date(),
    ])
  }

  async claimCompanionNotification(idempotencyKey, now = new Date(), leaseMs = 5 * 60 * 1000) {
    const leaseUntil = new Date(now.getTime() + leaseMs)
    const result = await this.pool.query(`UPDATE companion_notifications SET
      status = 'sending', attempts = attempts + 1, lease_until = $1, updated_at = $2
      WHERE idempotency_key = $3
        AND ((status IN ('pending', 'failed') AND available_at <= $2)
          OR (status = 'sending' AND lease_until <= $2)) RETURNING id`, [
      leaseUntil, now, idempotencyKey,
    ])
    return result.rowCount > 0
  }

  async finishCompanionNotification(idempotencyKey, { delivered, error = '', now = new Date() }) {
    if (delivered) {
      const result = await this.pool.query(`UPDATE companion_notifications SET
        status = 'delivered', delivered_at = $1, lease_until = NULL, last_error = '', updated_at = $1
        WHERE idempotency_key = $2 AND status = 'sending'`, [now, idempotencyKey])
      return result.rowCount > 0
    }
    const { rows } = await this.pool.query('SELECT attempts FROM companion_notifications WHERE idempotency_key = $1', [idempotencyKey])
    if (!rows[0]) return false
    const retryMinutes = Math.min(60, 5 * (2 ** Math.max(0, rows[0].attempts - 1)))
    const result = await this.pool.query(`UPDATE companion_notifications SET
      status = 'pending', available_at = $1, lease_until = NULL,
      last_error = $2, updated_at = $3
      WHERE idempotency_key = $4 AND status = 'sending'`, [
      new Date(now.getTime() + retryMinutes * 60000), String(error).slice(0, 350), now, idempotencyKey,
    ])
    return result.rowCount > 0
  }

  async listCompanionNotifications(limit = 50) {
    const { rows } = await this.pool.query(`SELECT id, idempotency_key AS "idempotencyKey",
      notification_type AS type, title, message, scheduled_at AS "scheduledAt",
      status, attempts, last_error AS error, created_at AS "createdAt",
      delivered_at AS "deliveredAt"
      FROM companion_notifications ORDER BY created_at DESC LIMIT $1`, [limit])
    return rows
  }

  async startCompanionRun(schedulerName, trigger, startedAt = new Date()) {
    const { rows } = await this.pool.query(`INSERT INTO companion_runs(
      scheduler_name, trigger, status, started_at
    ) VALUES ($1, $2, 'running', $3) RETURNING id`, [schedulerName, trigger, startedAt])
    return Number(rows[0].id)
  }

  async recoverInterruptedCompanionRuns(completedAt = new Date()) {
    const result = await this.pool.query(`UPDATE companion_runs SET status = 'interrupted',
      completed_at = $1, error = 'Process stopped during this run.'
      WHERE status = 'running'`, [completedAt])
    return result.rowCount
  }

  async getLastCompanionRun(schedulerName) {
    const { rows } = await this.pool.query(`SELECT id, scheduler_name AS "schedulerName",
      trigger, status, started_at AS "startedAt", completed_at AS "completedAt"
      FROM companion_runs
      WHERE scheduler_name = $1 AND trigger = 'external-cron' AND status != 'interval-not-due'
      ORDER BY id DESC LIMIT 1`, [schedulerName])
    return rows[0] || null
  }

  async finishCompanionRun(id, { status, deliveredCount = 0, error = '', completedAt = new Date() }) {
    const result = await this.pool.query(`UPDATE companion_runs SET status = $1, completed_at = $2,
      duration_ms = GREATEST(0, FLOOR(EXTRACT(EPOCH FROM ($2 - started_at)) * 1000))::integer,
      delivered_count = $3, error = $4 WHERE id = $5`, [
      status, completedAt, deliveredCount, String(error).slice(0, 350), id,
    ])
    return result.rowCount > 0
  }

  async listCompanionRuns(limit = 20) {
    const { rows } = await this.pool.query(`SELECT id, scheduler_name AS "schedulerName",
      trigger, status, started_at AS "startedAt", completed_at AS "completedAt",
      duration_ms AS "durationMs", delivered_count AS "deliveredCount", error
      FROM companion_runs ORDER BY id DESC LIMIT $1`, [limit])
    return rows
  }

  async getCompanionSchedulerStatus() {
    const lastRuns = await this.listCompanionRuns(20)
    const schedulers = {}
    for (const run of lastRuns) {
      if (!schedulers[run.schedulerName]) schedulers[run.schedulerName] = run
    }
    return { schedulers, lastRuns }
  }

  async getFestivalCalendar(region, year, now = new Date()) {
    const { rows } = await this.pool.query(`SELECT events_json AS events, fetched_at AS "fetchedAt"
      FROM companion_calendar_cache WHERE region = $1 AND year = $2`, [region, year])
    const row = rows[0]
    if (!row || now.getTime() - Date.parse(row.fetchedAt) > 86400000) return null
    return { events: row.events, fetchedAt: row.fetchedAt }
  }

  async saveFestivalCalendar(region, year, events, fetchedAt = new Date()) {
    await this.pool.query(`INSERT INTO companion_calendar_cache(region, year, events_json, fetched_at)
      VALUES ($1, $2, $3::jsonb, $4)
      ON CONFLICT (region, year) DO UPDATE SET
        events_json = EXCLUDED.events_json, fetched_at = EXCLUDED.fetched_at`, [
      region, year, JSON.stringify(events), fetchedAt,
    ])
  }

  async createLifeEvent(input = {}) {
    const event = normalizeLifeEvent(input)
    const { rows } = await this.pool.query(`INSERT INTO personal_events(
      title, description, category, event_date, event_time, timezone, recurrence,
      reminder_minutes_json, importance, active, next_occurrence
    ) VALUES ($1, $2, $3, $4, $5, $6, $7, $8::jsonb, $9, $10, $11)
    RETURNING id`, [
      event.title, event.description, event.category, event.eventDate, event.eventTime || '',
      event.timezone, event.recurrence, JSON.stringify(event.reminderMinutes),
      event.importance, Boolean(event.active), event.nextOccurrence || event.eventDate,
    ])
    return this.getLifeEvent(Number(rows[0].id))
  }

  async getLifeEvent(id) {
    const { rows } = await this.pool.query('SELECT * FROM personal_events WHERE id = $1', [id])
    return rows[0] ? deserializeLifeEvent(rows[0]) : null
  }

  async listLifeEvents() {
    const { rows } = await this.pool.query('SELECT * FROM personal_events ORDER BY next_occurrence, created_at DESC')
    return rows.map(deserializeLifeEvent)
  }

  async deleteLifeEvent(id) {
    const result = await this.pool.query('DELETE FROM personal_events WHERE id = $1', [id])
    return result.rowCount > 0
  }

  async updateLifeEvent(id, input = {}) {
    const current = await this.getLifeEvent(id)
    if (!current) return null
    const merged = { ...current, ...input }
    if (input.eventDate && input.eventDate !== current.eventDate && !Object.hasOwn(input, 'nextOccurrence')) {
      merged.nextOccurrence = input.eventDate
    }
    const next = normalizeLifeEvent(merged)
    await this.pool.query(`UPDATE personal_events SET title=$1, description=$2, category=$3,
      event_date=$4, event_time=$5, timezone=$6, recurrence=$7,
      reminder_minutes_json=$8::jsonb, importance=$9, active=$10,
      updated_at=now(), next_occurrence=$11 WHERE id=$12`, [
      next.title, next.description, next.category, next.eventDate, next.eventTime || '',
      next.timezone, next.recurrence, JSON.stringify(next.reminderMinutes),
      next.importance, Boolean(next.active), next.nextOccurrence || next.eventDate, id,
    ])
    return this.getLifeEvent(id)
  }

  async getDueLifeEvents(now = new Date()) {
    const events = await this.listLifeEvents()
    const due = []
    for (const event of events.filter((item) => item.active)) {
      for (const reminder of getDueEventReminders(event, now)) {
        const key = `event:${reminder.notificationKey}`
        const { rows } = await this.pool.query(`SELECT 1 FROM companion_notifications
          WHERE idempotency_key = $1 AND status = 'delivered'`, [key])
        if (!rows.length) due.push(reminder)
      }
    }
    return due
  }

  async advanceDueLifeEvents(now = new Date()) {
    let advanced = 0
    for (const event of (await this.listLifeEvents()).filter((item) => item.active && item.recurrence !== 'None')) {
      const occurrenceDate = event.nextOccurrence || event.eventDate
      const eventInstant = zonedDateTimeToDate(occurrenceDate, event.eventTime || '00:00', event.timezone)
      if (!Number.isFinite(eventInstant.getTime()) || eventInstant.getTime() > now.getTime()) continue
      let allDueNotificationsDelivered = true
      for (const reminderMinutes of event.reminderMinutes) {
        const elapsed = now.getTime() - (eventInstant.getTime() - reminderMinutes * 60000)
        if (elapsed < 0 || elapsed > 7 * 86400000) continue
        const key = `event:${event.id}:${occurrenceDate}:${reminderMinutes}`
        const { rows } = await this.pool.query('SELECT status FROM companion_notifications WHERE idempotency_key=$1', [key])
        if (rows[0]?.status !== 'delivered') {
          allDueNotificationsDelivered = false
          break
        }
      }
      if (!allDueNotificationsDelivered) continue
      const next = nextOccurrenceDate(occurrenceDate, event.recurrence)
      if (!next) continue
      await this.updateLifeEvent(event.id, { eventDate: next, nextOccurrence: next })
      advanced += 1
    }
    return advanced
  }

  async close() {
    await this.pool.end()
  }
}

function deserializeLifeEvent(row) {
  const reminderMinutes = Array.isArray(row.reminder_minutes_json)
    ? row.reminder_minutes_json
    : JSON.parse(row.reminder_minutes_json || '[]')
  const eventDate = typeof row.event_date === 'string'
    ? row.event_date.slice(0, 10)
    : row.event_date.toISOString().slice(0, 10)
  const nextOccurrence = typeof row.next_occurrence === 'string'
    ? row.next_occurrence.slice(0, 10)
    : row.next_occurrence.toISOString().slice(0, 10)
  return {
    id: Number(row.id),
    title: row.title,
    description: row.description,
    category: row.category,
    eventDate,
    eventTime: row.event_time,
    timezone: row.timezone || 'Asia/Kolkata',
    recurrence: row.recurrence || 'None',
    reminderMinutes: reminderMinutes.map(Number).filter(Number.isFinite),
    importance: row.importance || 'Medium',
    active: Boolean(row.active),
    createdAt: row.created_at,
    updatedAt: row.updated_at,
    lastNotifiedAt: row.last_notified_at || '',
    nextOccurrence,
  }
}
